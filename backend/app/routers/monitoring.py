
from datetime import date

from fastapi import APIRouter, Depends, HTTPException, Query

from app.auth_utils import get_current_user
from app.services.monitoring_service import (
    get_network_monitoring,
    get_station_monitoring,
)

router = APIRouter(
    prefix="/monitoring",
    tags=["Realtime Monitoring"],
)


@router.get("/summary")
def monitoring_summary(
    date: date | None = Query(
        default=None,
        description="Historical monitoring date, e.g. 2025-09-30",
    ),
    hour: int | None = Query(
        default=None,
        ge=0,
        le=23,
        description="Monitoring hour from 0 to 23",
    ),
    current_user=Depends(get_current_user),
):
    """Return observed historical data and ML predictions."""
    return get_network_monitoring(
        selected_date=date,
        selected_hour=hour,
    )


@router.get(
    "/live",
    summary="Live Monitoring",
    description="View station observations and ML demand predictions.",
)
def live_monitoring(
    current_user=Depends(get_current_user),
):
    try:
        result = get_network_monitoring()

        result["data_source"] = "historical_csv"
        result["is_live_feed"] = False
        result["observation_note"] = (
            "Counts are the latest observations available in the "
            "dataset. Predictions are generated by the trained ML "
            "model and are not observed passenger counts."
        )

        for snapshot in result.get("station_snapshots", []):
            snapshot["observed_entries"] = snapshot["current_ridership"]
            snapshot["observed_exits"] = snapshot["current_exit"]
            snapshot["predicted_demand"] = (
                snapshot["predicted_next_hour_ridership"]
            )

        return result

    except (FileNotFoundError, ValueError) as exc:
        raise HTTPException(
            status_code=503,
            detail=f"Monitoring data unavailable: {exc}",
        ) from exc


@router.get("/stations/{station}")
def station_monitoring(
    station: str,
    date: date | None = Query(
        default=None,
        description="Historical monitoring date, e.g. 2025-09-30",
    ),
    hour: int | None = Query(
        default=None,
        ge=0,
        le=23,
        description="Monitoring hour from 0 to 23",
    ),
    current_user=Depends(get_current_user),
):
    """Return a station's observations and ML prediction."""
    result = get_station_monitoring(
        station=station,
        selected_date=date,
        selected_hour=hour,
    )

    if result is None:
        raise HTTPException(
            status_code=404,
            detail=(
                f"No monitoring data found for station '{station}' "
                "at the selected date/hour."
            ),
        )

    return result




@router.get(
    "/demo-live",
    summary="Simulated Live Monitoring Demo",
    description=(
        "Simulated passenger activity for demonstration purposes. "
        "This is not a genuine live BMRCL data feed."
    ),
)
def demo_live_monitoring(
    current_user=Depends(get_current_user),
):
    from app.services.live_simulation_service import (
        get_live_network_monitoring,
    )

    try:
        result = get_live_network_monitoring()
        result["data_source"] = "historical_baseline_with_simulation"
        result["is_live_feed"] = False
        result["simulation"] = True
        result["demo_year"] = 2026
        result["observation_note"] = (
            "Demonstration only: passenger activity is simulated "
            "from historical monitoring results. These values are "
            "not actual 2026 BMRCL observations or live passenger counts."
        )
        return result

    except (FileNotFoundError, ValueError) as exc:
        raise HTTPException(
            status_code=503,
            detail=f"Demo monitoring unavailable: {exc}",
        ) from exc



